#!/usr/bin/env python3
"""!Writes the Qt part of the studio bundle's notices (notices/qt/) from a Qt source checkout (standard library only).

    python3 qt_notices.py QTBASE_DIR [--out notices/qt]

QTBASE_DIR is a checkout of qtbase at the Qt version PySide6 is pinned to (toolkit/requirements/ui.txt): every
qt_attribution.json under its src/ names a third-party part compiled into the Qt libraries, and LICENSES/ holds the
texts. This lists the parts that end up in the libraries a bundle ships (QtCore, QtGui, QtWidgets, QtDBus and the
platform plugins), copies each licence text they name, and adds Qt's and PySide6's own licences. Run it again when
the PySide6 pin changes; a sparse checkout is enough:

    git clone --depth 1 --branch v6.11.2 --filter=blob:none --sparse https://github.com/qt/qtbase.git
    git -C qtbase sparse-checkout set --no-cone /LICENSES '/src/**/qt_attribution.json'
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Any

## Source folders (below qtbase) whose parts are not in the shipped libraries: test support, other platforms,
## the SQL module (QtSql is excluded from bundles).
SKIPPED_PREFIXES = ("src/testlib", "src/testinternal", "src/3rdparty/wasm", "src/3rdparty/android",
                    "src/3rdparty/gradle", "src/3rdparty/sqlite", "src/plugins/sqldrivers")
## Licences of Qt and PySide6 themselves (the open-source options), always copied.
OWN_LICENCES = ("LGPL-3.0-only", "GPL-3.0-only", "GPL-2.0-only", "Qt-GPL-exception-1.0")
## Parts that are not in qtbase's attribution files but are in the PySide6 wheels' libraries.
EXTRA_PARTS = [
   {"Name": "PySide6 and Shiboken6 (Qt for Python)", "Version": "the PySide6 pin (toolkit/requirements/ui.txt)",
    "QtUsage": "The Python bindings: PySide6/*.abi3.*, libpyside6, shiboken6.",
    "LicenseId": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only", "Copyright": "Copyright (C) The Qt Company Ltd.",
    "Homepage": "https://code.qt.io/cgit/pyside/pyside-setup.git/"},
   {"Name": "International Components for Unicode (ICU)", "Version": "73 (Linux wheels only)",
    "QtUsage": "libicu*.so.73 next to the Qt libraries in Linux bundles (Unicode text handling in Qt Core).",
    "LicenseId": "Unicode-3.0", "Copyright": "Copyright (C) Unicode, Inc. and others.",
    "Homepage": "https://icu.unicode.org/"},
]
## Words in an SPDX expression that are not licence ids.
SPDX_OPERATORS = {"AND", "OR", "WITH"}
## Name of the generated list.
LIST_NAME = "QT_ATTRIBUTIONS.md"
## Folder (below the output) for the licence texts.
TEXTS = "licenses"

## A parsed attribution entry.
Entry = dict[str, Any]


def entries(qtbase: Path) -> list[Entry]:
   """!The attribution entries of the shipped parts, sorted by name.
   @param qtbase  the qtbase checkout
   @return list of entries (each with a "Where" key: its folder below qtbase)
   """
   out: list[Entry] = []
   for f in sorted(qtbase.glob("src/**/qt_attribution.json")):
      rel = f.parent.relative_to(qtbase).as_posix()
      if rel.startswith(SKIPPED_PREFIXES):
         continue
      # strict=False: some of Qt's files keep raw tabs inside strings.
      data = json.loads(f.read_text(encoding="utf-8"), strict=False)
      for e in data if isinstance(data, list) else [data]:
         e["Where"] = rel
         out.append(e)
   return sorted(out, key=lambda e: str(e.get("Name", "")).lower())


def licence_ids(expression: str) -> list[str]:
   """!The licence ids in an SPDX expression.
   @param expression  e.g. "BSD-3-Clause AND MIT"
   @return ids in order, without repeats
   """
   ids: list[str] = []
   for word in re.split(r"[\s()]+", expression):
      if word and word not in SPDX_OPERATORS and word not in ids:
         ids.append(word)
   return ids


def text_of(value: Any) -> str:
   """!A JSON field as one line (copyright lists are joined).
   @param value  str, list or None
   @return str
   """
   text = "; ".join(str(v) for v in value) if isinstance(value, list) else str(value or "")
   return " ".join(text.split())   # one line: some fields wrap inside the string


def write(qtbase: Path, out: Path) -> int:
   """!Writes the list and copies the texts.
   @param qtbase  the qtbase checkout
   @param out     output folder
   @return number of parts listed
   """
   parts = entries(qtbase) + EXTRA_PARTS
   wanted = list(OWN_LICENCES)
   for e in parts:
      wanted += [i for i in licence_ids(str(e.get("LicenseId", ""))) if i not in wanted]
   (out / TEXTS).mkdir(parents=True, exist_ok=True)
   missing = []
   for lid in wanted:
      src = qtbase / "LICENSES" / f"{lid}.txt"
      if src.is_file():
         shutil.copyfile(src, out / TEXTS / src.name)
      else:
         missing.append(lid)
   lines = ["# Qt and PySide6 in this bundle", "",
            "Generated by `toolkit/packaging/qt_notices.py` from Qt's own attribution files (qtbase "
            "`src/**/qt_attribution.json`); do not edit by hand.", "",
            "The studio bundle carries the Qt 6 libraries and PySide6 under the GNU LGPL version 3 "
            f"(`{TEXTS}/LGPL-3.0-only.txt`, which builds on `{TEXTS}/GPL-3.0-only.txt`). How to get Qt's source and "
            "how to replace the libraries: `QT_LGPL_NOTICE.md` beside this file.", "",
            "The parts below are compiled into those libraries; each licence text is in "
            f"`{TEXTS}/<licence id>.txt`.", ""]
   for e in parts:
      lines += [f"## {e.get('Name', e.get('Id', '?'))}", ""]
      for label, key in (("Version", "Version"), ("Used in Qt", "QtUsage"), ("Licence", "LicenseId"),
                         ("Copyright", "Copyright"), ("Home page", "Homepage"), ("Qt source folder", "Where")):
         value = text_of(e.get(key))
         if value:
            lines.append(f"- {label}: {value}")
      lines.append("")
   if missing:
      lines += ["## Licences without a text in Qt's LICENSES folder", "", *[f"- {m}" for m in missing], ""]
   (out / LIST_NAME).write_text("\n".join(lines), encoding="utf-8")
   return len(parts)


def main(argv: list[str] | None = None) -> int:
   """!Command-line entry point.
   @param argv  arguments without the program name, or None for sys.argv
   @return exit status
   """
   p = argparse.ArgumentParser(description="Writes the bundle's Qt notices from a qtbase checkout.")
   p.add_argument("qtbase", help="qtbase checkout (LICENSES/ and src/**/qt_attribution.json)")
   p.add_argument("--out", default=str(Path(__file__).resolve().parent / "notices" / "qt"), help="output folder")
   args = p.parse_args(argv)
   qtbase = Path(args.qtbase)
   if not (qtbase / "LICENSES").is_dir():
      sys.exit(f"qt_notices: {qtbase} has no LICENSES folder")
   count = write(qtbase, Path(args.out))
   print(f"qt_notices: {count} parts listed in {Path(args.out) / LIST_NAME}")
   return 0


if __name__ == "__main__":
   sys.exit(main())
